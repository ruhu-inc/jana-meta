def test_handwriting_counts_the_privacy_pass_when_it_ran_and_never_blocks_on_no_printed_text() -> None:
    ran = {"refusal": None, "privacy_available": False, "ocr_model_version": "4.1",
           "checks": [{"check": "no_text", "value": 0.0, "outcome": "blocking"},
                      {"check": "blur", "value": 10.0, "outcome": "blocking"}]}  # fmt: skip
    out = handwriting(ran)
    assert out["privacy_available"] is True
    assert [c["outcome"] for c in out["checks"]] == ["pass", "blocking"]  # a blurred photo is still refused
    assert handwriting({**ran, "ocr_model_version": None})["privacy_available"] is False  # the pass did not run
    assert handwriting({"refusal": "contains_person"}) == {"refusal": "contains_person"}


