"""Exact places on the student's own photo (JM-D10, SPEC §5): Muse Spark reads, SAM 3.1 outlines, Jana points.

Through the engine's photo reader with a scripted cloud provider that also answers the gateway's segment route: the
regions Spark boxes on its 0..1000 grid reach SAM as pixel box prompts on exactly the screened image; each mask comes
back as an outline and a tight box; uncertain lines are re-read once from their crops; nothing is guessed when SAM
finds nothing. Then lines of working keep their place on the photo, and a spoken cue at such a line lights the
student's own handwriting (`photo_region`). Every photo here is generated by the test."""

