def capture(texts: list[str]) -> dict[str, Any]:
    box = {"x": 0, "y": 0, "w": 1, "h": 1}
    return {"capture_id": CAP, "regions": [{"region_id": f"rgn_{i}", "text": t, "bbox": box}
                                           for i, t in enumerate(texts)]}  # fmt: skip


def test_board_lines_pair_with_the_photo_regions_they_came_from() -> None:
    lines = list(zip(STEPS, ["3x + 5 = 20", "3x = 25", "x = 25/3"], strict=True))
    # Same count: in order, even where the student corrected a line while confirming.
    assert photo_lines(capture(["3x + 5 = 20", "3x = 20 + 5", "x = 25/3"]), lines) == {
        STEPS[0]: f"{CAP}:rgn_0",
        STEPS[1]: f"{CAP}:rgn_1",
        STEPS[2]: f"{CAP}:rgn_2",
    }
    # Different counts: by text only, so nothing is pointed at a line it did not come from.
    assert photo_lines(capture(["Name: [blank]", "3x + 5 = 20", "x = 25/3", "check"]), lines) == {
        STEPS[0]: f"{CAP}:rgn_1",
        STEPS[2]: f"{CAP}:rgn_2",
    }


@dataclass
class _Step:
    step_id: str
    owner: str
    status: str


@dataclass
class _Board:
    steps: list[_Step]


@dataclass
class _State:
    board: _Board
    shown_visuals: list[dict[str, Any]] = field(default_factory=list)
    photo_lines: dict[str, str] = field(default_factory=dict)
    photo_marks: list[str] = field(default_factory=list)


def state() -> _State:
    steps = [
        _Step(s, "student", status) for s, status in zip(STEPS, ["correct", "incorrect", "incorrect"], strict=True)
    ]
    return _State(_Board(steps), photo_lines={STEPS[1]: f"{CAP}:rgn_1", STEPS[2]: f"{CAP}:rgn_2"})


@pytest.mark.parametrize("ref", [STEPS[1], "2", "line 2", "photo 2", "photo line 2", f"{CAP}:rgn_1"])
def test_a_cue_at_a_line_from_the_photo_lights_it_on_the_photo(ref: str) -> None:
    spoken = resolve(f'Look at <point at="{ref}"/>this line, where the sign changed.', Targets.of(state()))
    assert spoken.misses == () and [c.target for c in spoken.cues] == [f"{CAP}:rgn_1"]


def test_a_typed_line_and_unknown_photo_places_point_as_before_or_not_at_all() -> None:
    spoken = resolve('Here <point at="1"/>and here <point at="photo 1"/>and <point at="cap_' + ULID + ':rgn_9"/>.',
                     Targets.of(state()))  # fmt: skip
    assert [c.target for c in spoken.cues] == [STEPS[0]]  # line 1 was typed: the board line
    assert spoken.misses == ("photo_region_not_shown", "photo_region_not_shown")


def test_a_sketch_part_is_pointable_and_the_caption_contract_accepts_it() -> None:
    sketch_state = _State(_Board([]), photo_marks=[f"{CAP}:rgn_3"])
    spoken = resolve(f'Look at <point at="{CAP}:rgn_3"/>this arrow.', Targets.of(sketch_state))
    (cue,) = spoken.cues
