def test_spark_boxes_become_padded_pixel_prompts_inside_the_image() -> None:
    assert prompt_box({"x": 0.1, "y": 0.25, "w": 0.3, "h": 0.1}, 800, 600) == (72, 144, 328, 216)
    assert prompt_box({"x": 0.9, "y": 0.9, "w": 0.1, "h": 0.1}, 800, 600) == (712, 534, 800, 600)  # clamped
    assert prompt_box({"x": 0.5, "y": 0.5, "w": 0.0, "h": 0.0}, 800, 600) is not None  # padded, still a box


def test_a_mask_becomes_an_outline_and_a_tight_box_on_the_image() -> None:
    mask = bar(40, 10, inset=2)  # filled x 2..37, y 2..7
    assert rows_of(mask)[0] is None and rows_of(mask)[2] == (2, 37)
    polygon = outline(mask, [100, 50, 140, 60], 200, 100)
    assert polygon is not None and len(polygon) >= 4
    # Down the left edge, then back up the right edge (exclusive), closing on itself.
    assert polygon[0] == {"x": 0.51, "y": 0.52} and polygon[-1] == {"x": 0.69, "y": 0.53}
    assert {"x": 0.51, "y": 0.57} in polygon and {"x": 0.69, "y": 0.58} in polygon
    assert max(p["x"] for p in polygon) == 0.69  # the right edge, exclusive
    assert tight_box(mask, [100, 50, 140, 60], 200, 100) == {"x": 0.51, "y": 0.52, "w": 0.18, "h": 0.06}
    assert outline({"width": 3, "height": 3, "runs": [9]}, [0, 0, 3, 3], 10, 10) is None  # empty: nothing drawn


def test_an_outline_stays_small_for_a_tall_mask() -> None:
    polygon = outline(bar(30, 500), [0, 0, 30, 500], 30, 500)
    assert polygon is not None and len(polygon) <= 52


