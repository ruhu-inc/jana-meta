LOOP = asyncio.new_event_loop()
ULID = "01J8Z5W6X7Y8Z9A0B1C2D3E4F5"
CAP = f"cap_{ULID}"
STEPS = [f"stp_{ULID[:-1]}{c}" for c in "ABC"]


def run(coro: Any) -> Any:
    return LOOP.run_until_complete(coro)


def runs(mask: list[list[int]]) -> list[int]:
    flat = [v for row in mask for v in row]
    out, current, length = [], 0, 0
    for value in flat:
        if value != current:
            out.append(length)
            current, length = value, 0
        length += 1
    return [*out, length]


def bar(width: int, height: int, inset: int = 1) -> dict[str, Any]:
    """A filled mask with an empty `inset` border, as the gateway returns it."""
    rows = [
        [int(inset <= x < width - inset and inset <= y < height - inset) for x in range(width)] for y in range(height)
    ]
    return {"width": width, "height": height, "runs": runs(rows)}


def working_photo() -> bytes:
    image = Image.new("RGB", (800, 600), "white")
    out = io.BytesIO()
    image.save(out, "JPEG")
    return out.getvalue()


def line(order: int, text: str, y: int, confidence: float = 0.95) -> dict[str, Any]:
    return {"region_id": f"rgn_{order}", "kind": "working_line", "order": order, "text": text,
            "confidence": confidence, "needs_confirmation": False, "low_confidence_spans": [], "language": "en",
            "direction": "ltr", "bbox": {"x": 100, "y": y, "w": 500, "h": 120}, "number_label": None,
            "diagram_description": None, "table": None}  # fmt: skip


THREE_LINES = {"regions": [line(0, "3x + 5 = 20", 100), line(1, "3x = 20 + 5", 300),
                           {**line(2, "x = 25/3", 860), "bbox": {"x": 100, "y": 860, "w": 1001, "h": 140}}],
               "refusal": None}  # fmt: skip


@dataclass
class SegmentingCloud(ScriptedProvider):
    """The cloud provider, answering the gateway's segment route too (`GatewayProvider.segment`)."""

    segments: list[dict[str, Any]] = field(default_factory=list)
    answer: Any = None

    async def segment(self, body: dict[str, Any], timeout_s: float = 20.0) -> dict[str, Any]:
        self.segments.append(body)
        if isinstance(self.answer, Exception):
            raise self.answer
        if callable(self.answer):
            return self.answer(body)  # type: ignore[no-any-return]
        return {"objects": [], "images": 1}


def found_in_each_box(body: dict[str, Any]) -> dict[str, Any]:
    """SAM finding exactly the object inside each prompt box, inset by 4 pixels."""
    objects = []
    for prompt in body["objects"]:
        left, top, right, bottom = prompt["box"]
        box = [left + 4, top + 4, right - 4, bottom - 4]
        objects.append({"id": str(prompt["id"]), "box": box, "confidence": 0.9,
                        "mask": bar(box[2] - box[0], box[3] - box[1])})  # fmt: skip
    return {"objects": objects, "images": 1}


def reader(tmp_path: Path, regions: dict[str, Any], *, rereads: list[str] | None = None) -> tuple[Any, Any]:
    script: list[Any] = [reply(json.dumps(regions))]
    if rereads is not None:
        script.append(reply(json.dumps({"lines": rereads})))
    cloud = SegmentingCloud({"vision": script}, kind="cloud",
                            caps={"vision-model": replace(default_capabilities("cloud"), vision=True)})  # fmt: skip

    def configure(data: dict[str, Any]) -> None:
        data["cloud"]["enabled"] = True
        data["auxiliary"]["vision"]["model"] = "cloud:primary/vision-model"

    engine, _ = run(make_engine(tmp_path, {"vision": []}, overrides=configure, cloud=cloud, worker=False))
    engine.deps.router.cloud_on = lambda role: role == "vision"  # type: ignore[method-assign]
    return engine, cloud


def screened(photo: SafePhoto) -> SafePhoto:
    return photo  # the local privacy pass found nothing to mask on a blank page


def read(engine: Any) -> PhotoReading:
    reading: PhotoReading = run(engine.read_photo(working_photo(), send_to_cloud=True, screen=screened,
                                                  structured=True, purpose="working"))  # fmt: skip
    return reading


