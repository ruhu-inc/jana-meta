def test_spark_regions_are_outlined_by_sam_on_the_screened_photo(tmp_path: Path) -> None:
    engine, cloud = reader(tmp_path, THREE_LINES)
    cloud.answer = found_in_each_box
    try:
        reading = read(engine)
        assert reading.status == "read" and reading.outlined == 3 and reading.reread == 0
        (sent,) = cloud.segments
        assert sent["width"] == 800 and sent["height"] == 600 and sent["image"].startswith("data:image/jpeg;base64,")
        assert [o["id"] for o in sent["objects"]] == [0, 1, 2]
        # Spark's 0..1000 grid in the image's own pixels, padded; a box reaching 1001 clamps to the image's edge.
        assert sent["objects"][0]["box"] == [72, 54, 488, 138]
        assert sent["objects"][2]["box"][2:] == [800, 600]
        assert reading.regions is not None
        for region in reading.regions:
            assert len(region["outline"]) >= 3
            assert 0 <= region["bbox"]["x"] and region["bbox"]["x"] + region["bbox"]["w"] <= 1
        # The image SAM saw is exactly the one Spark read: the screened image, never the original.
        (read_request,) = [r for r in cloud.requests if r.get("_role") == "vision"]
        image_part = next(p for m in read_request["messages"] for p in m["content"] if p.get("type") == "image_url")
        assert image_part["image_url"]["url"] == sent["image"]
    finally:
        run(close(engine))


def test_no_match_or_a_failed_segmentation_leaves_spark_regions_unguessed(tmp_path: Path) -> None:
    for answer in ({"objects": [], "images": 1}, RuntimeError("gateway down")):
        engine, cloud = reader(tmp_path, THREE_LINES)
        cloud.answer = answer
        try:
            reading = read(engine)
            assert reading.status == "read" and reading.outlined == 0
            assert reading.regions is not None and all("outline" not in r for r in reading.regions)
            assert reading.regions[0]["bbox"] == {"x": 0.1, "y": 0.1, "w": 0.5, "h": 0.12}
        finally:
            run(close(engine))


def test_a_low_confidence_mask_is_not_shown(tmp_path: Path) -> None:
    engine, cloud = reader(tmp_path, THREE_LINES)

    def weak(body: dict[str, Any]) -> dict[str, Any]:
        reply_ = found_in_each_box(body)
        reply_["objects"][1]["confidence"] = 0.2
        return reply_

    cloud.answer = weak
    try:
        reading = read(engine)
        assert reading.outlined == 2 and reading.regions is not None and "outline" not in reading.regions[1]
    finally:
        run(close(engine))


def test_an_uncertain_line_is_reread_once_from_its_crop(tmp_path: Path) -> None:
    unsure = {"regions": [line(0, "3x + 5 = 20", 100), line(1, "3x = 20 [?] 5", 300, 0.6),
                          line(2, "x = 25/3", 500)], "refusal": None}  # fmt: skip
    engine, cloud = reader(tmp_path, unsure, rereads=["3x = 20 + 5"])
    cloud.answer = found_in_each_box
    try:
        reading = read(engine)
        assert reading.reread == 1 and reading.regions is not None
        assert reading.regions[1]["text"] == "3x = 20 + 5" and reading.regions[1]["needs_confirmation"] is True
        vision_calls = [r for r in cloud.requests if r.get("_role") == "vision"]
        assert len(vision_calls) == 2  # the read and one re-read, never more
        crop_images = [p for m in vision_calls[1]["messages"] for p in m["content"] if p.get("type") == "image_url"]
        assert len(crop_images) == 1
        with Image.open(
            io.BytesIO(__import__("base64").b64decode(crop_images[0]["image_url"]["url"].split(",")[1]))
        ) as c:
            assert c.width < 800 and c.height < 200  # the line's crop, not the page
    finally:
        run(close(engine))


def test_a_reread_that_is_still_unsure_changes_nothing() -> None:
    regions = [{"text": "3x = 20 [?] 5", "low_confidence_spans": [{"start": 7, "end": 10}], "needs_confirmation": True}]
    assert merge_rereads(regions, [0], ["3x = 2[?] + 5"]) == 0 and regions[0]["text"] == "3x = 20 [?] 5"
    assert merge_rereads(regions, [0], [""]) == 0


